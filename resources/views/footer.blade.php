    $(document).ready(function() {
        function normalizeText(value) {
            return (value || '').toString().toLowerCase().replace(/[^a-z0-9]/g, '');
        }

        function levenshtein(a, b) {
            a = normalizeText(a);
            b = normalizeText(b);
            if (a === b) return 0;
            if (!a.length) return b.length;
            if (!b.length) return a.length;

            const matrix = [];
            for (let i = 0; i <= b.length; i++) matrix[i] = [i];
            for (let j = 0; j <= a.length; j++) matrix[0][j] = j;

            for (let i = 1; i <= b.length; i++) {
                for (let j = 1; j <= a.length; j++) {
                    matrix[i][j] = b.charAt(i - 1) === a.charAt(j - 1)
                        ? matrix[i - 1][j - 1]
                        : Math.min(matrix[i - 1][j - 1] + 1, matrix[i][j - 1] + 1, matrix[i - 1][j] + 1);
                }
            }

            return matrix[b.length][a.length];
        }

        function respondentMatcher(params, data) {
            if ($.trim(params.term) === '') {
                return data;
            }

            if (!data.text) {
                return null;
            }

            const term = normalizeText(params.term);
            const text = normalizeText(data.text);

            if (text.indexOf(term) > -1 || term.indexOf(text) > -1 || levenshtein(term, text) <= 2) {
                return data;
            }

            return null;
        }

        function fillRespondentFields(option) {
            if (!option || !option.dataset) {
                $('#user_css_id, #email, #hp, #bidang, #perusahaan, #treg, #status, #lab').val('');
                return;
            }

            $('#user_css_id').val(option.dataset.userId || '');
            $('#email').val(option.dataset.email || '');
            $('#hp').val(option.dataset.hp || '');
            $('#bidang').val(option.dataset.bidang || '');
            $('#perusahaan').val(option.dataset.perusahaan || '');
            $('#treg').val(option.dataset.treg || '');
            $('#status').val(option.dataset.status || '');
            $('#lab').val(option.dataset.lab || '');
        }

        $('#nama').select2({
            placeholder: 'Pilih Nama....',
            allowClear: true,
            tags: true,
            matcher: respondentMatcher,
            width: '100%'
        });
        
        // Ketika nilai select berubah
        $('#nama').on('select2:select', function(e) {
            const data = e.params.data;
