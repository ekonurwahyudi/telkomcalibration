    $(document).ready(function() {
        $('#ttm-contactform-2').submit(function(event) {
            if (isNameDuplicate()) {
                event.preventDefault();
                $('#nameExistsAlert').show();
            }
        });

        $('#nama').change(function() {
            $('#nameExistsAlert').hide();
        });

        $('#hp').on('input', function() {
            $('#nameExistsAlert').hide();
        });

        function isNameDuplicate() {
            var nama = $('#nama').val();
            var hp = $('#hp').val();
            var userCssId = $('#user_css_id').val();

            var isDuplicate = false;

            $.ajax({
                url: "{{ route('form.checkName') }}",
                type: "GET",
                data: { nama: nama, hp: hp, user_css_id: userCssId },
                async: false,
                success: function(response) {
                    if (typeof response === 'object') {
                        isDuplicate = !!response.duplicate;
                    } else {
                        isDuplicate = !!response;
                    }
                }
            });

            return isDuplicate;
        }
    });
</script>
